"""
Experiment A follow-up: is the difference between the two guard builds caused by
small differences in prompt formatting?

The official prompt and Ollama's template differ only in whitespace. So we run the
OFFICIAL weights twice on the same sample, once with each format, and compare with
the verdicts already saved for both builds.
  * format changes little  -> the difference comes from the build itself
  * format changes a lot   -> the guard is sensitive to whitespace (a finding too)

Usage:  python scripts/guard_prompt_format_test.py [--n 300]
"""
import argparse
import os
import sys

import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from eval_llamaguard import load_model, parse_verdict, render  # noqa: E402
from evaluate import md_table  # noqa: E402


def to_ollama_format(prompt):
    """Apply the whitespace of Ollama's template to the official prompt."""
    out = prompt.replace(" <|eot_id|>", "<|eot_id|>").replace("<|begin_of_text|>", "")
    return out.rstrip() if out.rstrip().endswith("<|end_header_id|>") else out


def verdicts(tok, model, device, prompts, batch_size=16):
    import torch
    out = []
    for i in range(0, len(prompts), batch_size):
        enc = tok(prompts[i:i + batch_size], return_tensors="pt", padding=True,
                  add_special_tokens=False).to(device)
        with torch.inference_mode():
            gen = model.generate(**enc, max_new_tokens=10, do_sample=False, pad_token_id=tok.pad_token_id)
        out += [parse_verdict(tok.decode(g, skip_special_tokens=True))
                for g in gen[:, enc["input_ids"].shape[1]:]]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=300, help="prompts per variant")
    args = ap.parse_args()
    rd = os.path.join(ROOT, "results")
    data = pd.read_csv(os.path.join(ROOT, "data", "processed", "veilbreak_v2.csv"))
    d = data[data.split == "eval"]
    saved = {}
    for name, f in (("ollama", "llamaguard_predictions_ollama.csv"), ("official", "llamaguard_predictions.csv")):
        lg = pd.read_csv(os.path.join(rd, f))
        saved[name] = lg[lg["input"] == "raw"].set_index("id")["pred"]

    tok, model, device = load_model("meta-llama/Llama-Guard-3-1B")
    rows = []
    for variant in ("plain", "base64", "composed", "caesar3"):
        s = d[d.variant == variant].sample(args.n, random_state=42)
        official_prompts = [render(tok, t, True) for t in s.text]
        a = verdicts(tok, model, device, official_prompts)
        b = verdicts(tok, model, device, [to_ollama_format(p) for p in official_prompts])
        flag = lambda v: pd.Series(v, index=s.index) == "unsafe"     # noqa: E731
        fa, fb = flag(a), flag(b)
        ol = s["id"].map(saved["ollama"]) == "unsafe"
        of = s["id"].map(saved["official"]) == "unsafe"
        rows.append([variant, args.n, f"{100 * of.mean():.1f}%", f"{100 * fa.mean():.1f}%", f"{100 * fb.mean():.1f}%",
                     f"{100 * ol.mean():.1f}%", f"{100 * (fa == fb).mean():.1f}%", f"{100 * (fb == ol).mean():.1f}%"])
    L = ["# Experiment A follow-up: does prompt formatting explain the difference?\n",
         "_Generated by `scripts/guard_prompt_format_test.py` — do not edit by hand._\n",
         "Harmful and safe prompts together; \"flagged\" means a full `unsafe` reply.\n",
         md_table(["variant", "n", "flagged: official (saved)", "flagged: official weights, official format",
                   "flagged: official weights, Ollama format", "flagged: Ollama (saved)",
                   "same verdict across formats", "official weights in Ollama format vs Ollama"], rows), ""]
    with open(os.path.join(rd, "GUARD_FORMAT_TEST.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
