"""
Experiment A: do two builds of the same guard give the same verdicts?

Same model name (Llama Guard 3 1B), same prompts, two ways of running it:
  ollama   : quantized build served by Ollama
  official : Meta's full-precision weights through transformers

People often assume a quantized guard behaves like the original. Here we measure
it, separately for plain and encoded text, on the raw prompts only (no decoding).

What this can and cannot show: the two setups also differ in software and possibly
prompt formatting, so a difference is a difference between BUILDS. It is not proof
that quantization alone caused it.

Usage:  python scripts/compare_guard_builds.py
Needs:  results/llamaguard_predictions_ollama.csv (saved from commit 47f412f)
        results/llamaguard_predictions.csv        (official weights)
"""
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from evaluate import ADDED_LATER, IN_SCOPE, OUT_SCOPE, boot, md_table  # noqa: E402


def load(path):
    lg = pd.read_csv(path)
    return lg[lg["input"] == "raw"].set_index("id")["pred"]


def main():
    rd = os.path.join(ROOT, "results")
    old, new = load(os.path.join(rd, "llamaguard_predictions_ollama.csv")), \
        load(os.path.join(rd, "llamaguard_predictions.csv"))
    data = pd.read_csv(os.path.join(ROOT, "data", "processed", "veilbreak_v2.csv"))
    d = data[(data.split == "eval") & data["id"].isin(old.index) & data["id"].isin(new.index)].copy()
    d["old"], d["new"] = d["id"].map(old), d["id"].map(new)
    assert not d[["old", "new"]].isin(["error"]).any().any(), "error replies: fix them first"

    rng = np.random.default_rng(42)
    d["old_flag"], d["new_flag"] = d.old == "unsafe", d.new == "unsafe"    # strict rule
    rows = []
    for v in IN_SCOPE + ADDED_LATER + OUT_SCOPE:
        s = d[d.variant == v]
        agree, lo, hi = boot((s.old_flag == s.new_flag).values, rng)
        u, b = s[s.label == "unsafe"], s[s.label == "safe"]
        rows.append([v, len(s), f"{100 * agree:.1f}% [{100 * lo:.1f}–{100 * hi:.1f}]",
                     f"{100 * u.old_flag.mean():.1f}%", f"{100 * u.new_flag.mean():.1f}%",
                     f"{100 * b.old_flag.mean():.1f}%", f"{100 * b.new_flag.mean():.1f}%",
                     int((s.old == "code_only").sum()), int((s.new == "code_only").sum())])
    L = ["# Experiment A: same guard, two builds\n",
         "_Generated by `scripts/compare_guard_builds.py` — do not edit by hand._\n",
         f"- Llama Guard 3 1B: Ollama quantized build vs official weights, raw prompts, {d.group_id.nunique()} prompt groups.",
         "- \"Flagged\" means a full `unsafe` reply; a bare hazard code counts as not flagged.",
         "- A difference is between builds. It does not prove quantization alone caused it.\n",
         md_table(["variant", "n", "same verdict", "caught: Ollama", "caught: official",
                   "safe flagged: Ollama", "safe flagged: official", "bare codes: Ollama", "bare codes: official"], rows), ""]
    with open(os.path.join(rd, "GUARD_BUILDS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
